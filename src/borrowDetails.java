    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String name = borrowerName.getText().trim();
        String id = borrowerID.getText().trim();
        String institute = insti.getSelectedItem().toString();
        String bookTitle = bookName.getText().trim();
        
        if (name.isEmpty() || id.isEmpty() || bookTitle.isEmpty() || institute.equalsIgnoreCase("Institute")) {
            javax.swing.JOptionPane.showMessageDialog(
            this, "Please complete all fields.");
            
            return;
        }
        
        library.borrowBook(name, id, institute, bookTitle);
        javax.swing.JOptionPane.showMessageDialog(
        this, "Book borrowing successfully recorded!");
        
        dispose();
    }//GEN-LAST:event_jButton1ActionPerformed


